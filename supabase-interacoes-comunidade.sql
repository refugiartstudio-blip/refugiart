-- Interações das publicações das comunidades RefugiART
-- Execute este arquivo no Supabase > SQL Editor > New query.

create table if not exists public.community_post_likes (
  id bigint generated by default as identity primary key,
  post_id text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (post_id, user_id)
);

create table if not exists public.community_post_interest (
  id bigint generated by default as identity primary key,
  post_id text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (post_id, user_id)
);

create table if not exists public.community_post_comments (
  id bigint generated by default as identity primary key,
  post_id text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  content text not null check (char_length(trim(content)) between 1 and 1000),
  created_at timestamptz not null default now()
);

create index if not exists community_post_likes_post_idx on public.community_post_likes(post_id);
create index if not exists community_post_interest_post_idx on public.community_post_interest(post_id);
create index if not exists community_post_comments_post_idx on public.community_post_comments(post_id, created_at);

alter table public.community_post_likes enable row level security;
alter table public.community_post_interest enable row level security;
alter table public.community_post_comments enable row level security;

drop policy if exists "likes public read" on public.community_post_likes;
create policy "likes public read" on public.community_post_likes for select using (true);
drop policy if exists "likes own insert" on public.community_post_likes;
create policy "likes own insert" on public.community_post_likes for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "likes own delete" on public.community_post_likes;
create policy "likes own delete" on public.community_post_likes for delete to authenticated using (auth.uid() = user_id);

drop policy if exists "interest public read" on public.community_post_interest;
create policy "interest public read" on public.community_post_interest for select using (true);
drop policy if exists "interest own insert" on public.community_post_interest;
create policy "interest own insert" on public.community_post_interest for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "interest own delete" on public.community_post_interest;
create policy "interest own delete" on public.community_post_interest for delete to authenticated using (auth.uid() = user_id);

drop policy if exists "comments public read" on public.community_post_comments;
create policy "comments public read" on public.community_post_comments for select using (true);
drop policy if exists "comments own insert" on public.community_post_comments;
create policy "comments own insert" on public.community_post_comments for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "comments own delete" on public.community_post_comments;
create policy "comments own delete" on public.community_post_comments for delete to authenticated using (auth.uid() = user_id);
